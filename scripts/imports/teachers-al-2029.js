// One-time content upgrade. Existing IDs, videos, publication choices and unrelated
// classes survive. The API stores the complete pre-import data as a recovery copy.
export function mergeAlTeachers(data){
 const next=structuredClone(data);
 if(next.completedImports?.includes(AL_IMPORT))return next;
 for(const teacher of alTeachers){
  const current=next.teachers.find(t=>t.id===teacher.id||(t.programme==='al'&&t.name.trim()===teacher.name.trim()));
  if(!current){next.teachers.push(structuredClone(teacher));continue;}
  const customNotes=current.notes&&!current.notes.startsWith('PDF හි සඳහන්')?current.notes:'';
  const keep={id:current.id,name:current.name,media:current.media,published:current.published,
   schedule:current.schedule.filter(row=>!row.grade.includes('2029'))};
  Object.assign(current,structuredClone(teacher),keep);
  if(customNotes)current.notes=[teacher.notes,customNotes].filter(Boolean).join('\n\n');
 }
 next.completedImports=[...(next.completedImports||[]),AL_IMPORT];
 return next;
}
